// bd index — regenerate (or --check) the ADR, spec, change and tool indexes.
// Validates frontmatter so agents get a fast, deterministic signal instead of re-reading docs.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, basename, dirname, relative } from 'node:path';
import { loadDocs, list, str, type Doc } from '../lib/frontmatter.ts';

const ROOT = process.cwd();
const GEN = '<!-- GENERATED by `pnpm bd index` from frontmatter. Do not edit by hand. -->';
const ADR_STATUSES = ['proposed', 'accepted', 'deferred', 'rejected', 'superseded', 'deprecated'];
const SPEC_STATUSES = ['draft', 'active', 'deprecated'];
const CHANGE_STATUSES = ['proposed', 'approved', 'in-progress', 'done', 'abandoned'];

const errors: string[] = [];
const outputs = new Map<string, string>();
const isIndex = (p: string) => basename(p) === 'README.md';
const rel = (from: string, to: string) => relative(dirname(from), to).replaceAll('\\', '/');
const need = (d: Doc, keys: string[]) => keys.forEach(k => { if (!str(d.meta[k])) errors.push(`${d.path}: missing '${k}'`); });

// ---------- ADRs ----------
const adrDir = 'docs/decisions';
const { docs: adrs, errors: adrErr } = loadDocs(ROOT, adrDir, isIndex);
errors.push(...adrErr);
const adrById = new Map<string, Doc>();
for (const d of adrs) {
  need(d, ['id', 'title', 'status', 'date', 'domain']);
  const id = str(d.meta.id), domain = str(d.meta.domain), status = str(d.meta.status);
  const folder = basename(dirname(d.path));
  if (folder !== domain) errors.push(`${d.path}: domain '${domain}' does not match folder '${folder}'`);
  if (!id.startsWith(domain.toUpperCase() + '-')) errors.push(`${d.path}: id '${id}' must start with '${domain.toUpperCase()}-'`);
  if (!basename(d.path).startsWith(id + '-')) errors.push(`${d.path}: filename must start with '${id}-'`);
  if (!ADR_STATUSES.includes(status)) errors.push(`${d.path}: status '${status}' not in ${ADR_STATUSES.join('|')}`);
  if (adrById.has(id)) errors.push(`${d.path}: duplicate id ${id}`);
  adrById.set(id, d);
}
for (const d of adrs) {
  for (const s of list(d.meta.supersedes)) if (!adrById.has(s)) errors.push(`${d.path}: supersedes unknown ${s}`);
  const by = str(d.meta.superseded_by);
  if (str(d.meta.status) === 'superseded' && !by) errors.push(`${d.path}: status superseded needs superseded_by`);
  if (by && !adrById.has(by)) errors.push(`${d.path}: superseded_by unknown ${by}`);
}
const domains = [...new Set(adrs.map(d => str(d.meta.domain)))].sort();
const adrRow = (from: string) => (d: Doc) =>
  `| [${str(d.meta.id)}](${rel(from, d.path)}) | ${str(d.meta.title)} | **${str(d.meta.status)}** | ${str(d.meta.date)} | ${list(d.meta.tags).join(', ')} |`;
const head = '| ID | Decision | Status | Date | Tags |\n|---|---|---|---|---|';
{
  const target = `${adrDir}/README.md`;
  const counts = ADR_STATUSES.map(s => `${s}: ${adrs.filter(d => str(d.meta.status) === s).length}`).join(' · ');
  let md = `${GEN}\n# Architecture Decision Records\n\nDomain-organised ADRs. One decision per file, with explicit status in frontmatter.\n` +
    `Create one with \`pnpm bd new adr <domain> "Title"\`. Statuses: ${ADR_STATUSES.map(s => '`' + s + '`').join(', ')}.\n\n**${adrs.length} decisions** · ${counts}\n`;
  for (const dom of domains) {
    const rows = adrs.filter(d => str(d.meta.domain) === dom).map(adrRow(target));
    md += `\n## [${dom}](${dom}/README.md)\n\n${head}\n${rows.join('\n')}\n`;
    const dt = `${adrDir}/${dom}/README.md`;
    outputs.set(dt, `${GEN}\n# ${dom} decisions\n\n[All domains](../README.md)\n\n${head}\n${adrs.filter(d => str(d.meta.domain) === dom).map(adrRow(dt)).join('\n')}\n`);
  }
  outputs.set(target, md);
}

// ---------- Specs & changes ----------
const { docs: specs, errors: sErr } = loadDocs(ROOT, 'docs/specs/domains', isIndex);
const { docs: changeDocs, errors: cErr } = loadDocs(ROOT, 'docs/specs/changes', p => basename(p) !== 'proposal.md');
errors.push(...sErr, ...cErr);
const checkRefs = (d: Doc) => list(d.meta.adrs).forEach(a => { if (!adrById.has(a)) errors.push(`${d.path}: references unknown ADR ${a}`); });
const specIds = new Set<string>();
for (const d of specs) {
  need(d, ['id', 'title', 'status', 'domain']);
  if (!SPEC_STATUSES.includes(str(d.meta.status))) errors.push(`${d.path}: status not in ${SPEC_STATUSES.join('|')}`);
  if (basename(dirname(d.path)) !== str(d.meta.domain)) errors.push(`${d.path}: domain does not match folder`);
  specIds.add(str(d.meta.id)); checkRefs(d);
}
for (const d of changeDocs) {
  need(d, ['id', 'title', 'status']);
  if (!CHANGE_STATUSES.includes(str(d.meta.status))) errors.push(`${d.path}: status not in ${CHANGE_STATUSES.join('|')}`);
  for (const s of list(d.meta.specs)) if (!specIds.has(s)) errors.push(`${d.path}: references unknown spec ${s}`);
  checkRefs(d);
}
{
  const target = 'docs/specs/README.md';
  const sRow = (d: Doc) => `| [${str(d.meta.id)}](${rel(target, d.path)}) | ${str(d.meta.title)} | ${str(d.meta.domain)} | **${str(d.meta.status)}** | ${list(d.meta.adrs).join(', ')} |`;
  const cRow = (d: Doc) => `| [${str(d.meta.id)}](${rel(target, d.path)}) | ${str(d.meta.title)} | **${str(d.meta.status)}** | ${list(d.meta.specs).join(', ')} |`;
  outputs.set(target, `${GEN}\n# Specs\n\n- **domains/**: living behaviour specs, the source of truth for *what* the system does. Statuses: ${SPEC_STATUSES.join(', ')}.\n` +
    `- **changes/**: proposals for units of work (proposal.md + tasks.md). Statuses: ${CHANGE_STATUSES.join(', ')}.\n- **templates/**: copy via \`pnpm bd new spec|change\`.\n\n` +
    `## Domain specs\n\n| ID | Spec | Domain | Status | ADRs |\n|---|---|---|---|---|\n${specs.map(sRow).join('\n')}\n\n` +
    `## Changes\n\n| ID | Change | Status | Specs |\n|---|---|---|---|\n${changeDocs.map(cRow).join('\n')}\n`);
}

// ---------- Tools ----------
{
  const rows: string[] = [];
  for (const dir of readdirSync('tools').sort()) {
    const manifest = join('tools', dir, 'tool.json');
    if (!statSync(join('tools', dir)).isDirectory() || !existsSync(manifest)) continue;
    try {
      const t = JSON.parse(readFileSync(manifest, 'utf8'));
      for (const k of ['name', 'summary', 'usage']) if (!t[k]) errors.push(`${manifest}: missing '${k}'`);
      rows.push(`| \`${t.name}\` | ${t.summary} | ${(t.usage ?? []).map((u: string) => '`' + u + '`').join('<br>')} | ${t.outputs ?? ''} |`);
    } catch (e) { errors.push(`${manifest}: ${(e as Error).message}`); }
  }
  outputs.set('tools/README.md', `${GEN}\n# Tool registry\n\nDeterministic, reusable tools. **Check here before writing a new script.** If a task repeats, turn it into a tool:\n` +
    `add \`tools/<name>/index.ts\` and \`tools/<name>/tool.json\`, then run \`pnpm bd index\`. Every tool runs as \`pnpm bd <name> ...\`.\n\n` +
    `| Tool | Purpose | Usage | Outputs |\n|---|---|---|---|\n${rows.join('\n')}\n`);
}

// ---------- write / check ----------
const check = process.argv.includes('--check');
let stale = 0;
for (const [p, content] of outputs) {
  const cur = existsSync(p) ? readFileSync(p, 'utf8') : '';
  if (cur === content) continue;
  if (check) { stale++; console.error(`stale: ${p}`); } else { writeFileSync(p, content); console.log(`wrote ${p}`); }
}
for (const e of errors) console.error(`error: ${e}`);
const summary = { adrs: adrs.length, specs: specs.length, changes: changeDocs.length, errors: errors.length, stale };
console.log(JSON.stringify(summary));
if (errors.length || stale) process.exit(1);
