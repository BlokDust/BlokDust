// The comment rule (owner, CHG-0045): prefer descriptive names to comments. A comment block has at
// most two lines, each line at most 100 characters. Lines that only cite IDs are always allowed.
import { existsSync, readFileSync } from 'node:fs';
import type { Finding } from '../lint/baseline.ts';
import { commentBlocks, syntaxOf, type CommentLine } from './scan.ts';

export const MAX_BLOCK_LINES = 2;
export const MAX_LINE_LENGTH = 100;
export const BLOCK_RULE = 'comment-block-lines';
export const LENGTH_RULE = 'comment-line-length';

// SIMULATION-0001, CHG-0045, SPEC-CONNECTIONS-PROXIMITY R5, PLUGIN-0004 R2b …
const ID = String.raw`[A-Z][A-Z0-9]*(?:-[A-Z0-9]+)+(?:\s+R\d+[a-z]?)?`;
const ID_ONLY = new RegExp(String.raw`^(?:${ID})(?:[\s,;:.()/]+(?:${ID}))*[\s,;:.()]*$`);
// Tool directives and markers that must stay where they are.
const DIRECTIVE =
  /^(eslint-|@ts-|prettier-ignore|NOLINT|clang-format|clang-tidy|c8 |istanbul |!|<reference|GENERATED|@generated|#region|#endregion)/;

const SKIPPED =
  /(^|\/)(node_modules|\.cache|build|dist|output)\/|^web\/src\/v1ui\/ported\/|(^|\/)generated\/|^tests\/(golden|visual\/reference|visual\/fixtures)\/|^web\/public\//;

export const exempt = (text: string) => ID_ONLY.test(text) || DIRECTIVE.test(text);

export function checksComments(file: string): boolean {
  return syntaxOf(file) !== undefined && !SKIPPED.test(file);
}

function blockFindings(file: string, lines: CommentLine[]): Finding[] {
  const counted = lines.filter((entry) => !exempt(entry.text));
  const findings: Finding[] = [];
  const first = counted.at(0);
  if (first && counted.length > MAX_BLOCK_LINES) {
    findings.push({
      file,
      line: first.line,
      rule: BLOCK_RULE,
      message: `comment block of ${counted.length} lines (at most ${MAX_BLOCK_LINES}): name things instead, or shorten it`,
    });
  }
  for (const entry of counted) {
    if (entry.physicalLength > MAX_LINE_LENGTH) {
      findings.push({
        file,
        line: entry.line,
        rule: LENGTH_RULE,
        message: `comment line of ${entry.physicalLength} characters (at most ${MAX_LINE_LENGTH})`,
      });
    }
  }
  return findings;
}

export function commentFindings(file: string): Finding[] {
  const syntax = syntaxOf(file);
  if (!syntax || !existsSync(file)) return [];
  const source = readFileSync(file, 'utf8');
  const header = source.split('\n', 3).join('\n');
  if (/GENERATED by|@generated|Do not edit by hand/.test(header)) return [];
  return commentBlocks(source, syntax).flatMap((block) => blockFindings(file, block.lines));
}
