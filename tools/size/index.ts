// bd size: no agent-written file grows past about 5,000 tokens (owner, 2026-11-20). A big file costs every agent that
// reads it, and most reads only need part of it. Files over the limit today are in baseline.json and may only shrink.
//   pnpm bd size check [--staged]   every tracked file, or (the pre-commit hook) what is staged
//   pnpm bd size baseline           write baseline.json from the files over the limit now (after splitting one)
//   pnpm bd size install            set the clone's pre-commit hook (bd size + bd lint, tools/lib/pre-commit-hook.ts)
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { installPreCommitHook } from '../lib/pre-commit-hook.ts';

export const LIMIT_TOKENS = 5000;
const BYTES_PER_TOKEN = 4;  // an estimate: code tokenises a little denser, prose a little looser
const BASELINE = 'tools/size/baseline.json';
/** Agent-written text. Data (JSON, goldens), lockfiles, images and generated or ported files are not counted. */
const COUNTED = /\.(ts|tsx|js|mjs|cjs|cpp|cc|c|h|hpp|mm|m|swift|py|sh|css|html|md|cmake|in)$|(^|\/)CMakeLists\.txt$/;
const SKIPPED = /(^|\/)(node_modules|\.cache|build|dist|output)\/|^web\/src\/v1ui\/ported\/|(^|\/)generated\/|^tests\/(golden|visual\/reference|visual\/fixtures)\/|(^|\/)(LICENSE|NOTICE)[^/]*$|^web\/public\//;

const git = (...args: string[]) => spawnSync('git', args, { encoding: 'utf8', maxBuffer: 256 << 20 });
const tokens = (bytes: number) => Math.ceil(bytes / BYTES_PER_TOKEN);
/** Generated files say so at the top (bd codegen, bd v1 port-ui, …). */
const generated = (text: string) => /GENERATED by|@generated|Do not edit by hand/.test(text.split('\n', 3).join('\n'));
export function counted(file: string, text: string): boolean { return COUNTED.test(file) && !SKIPPED.test(file) && !generated(text); }

type Baseline = Record<string, number>;  // file → tokens it may not grow past
const readBaseline = (): Baseline => (existsSync(BASELINE) ? JSON.parse(readFileSync(BASELINE, 'utf8')) : {});

function files(staged: boolean): { file: string; text: string }[] {
  if (staged) {
    const names = git('diff', '--cached', '--name-only', '--diff-filter=ACMR', '-z').stdout.split('\0').filter(Boolean);
    return names.map(file => ({ file, text: git('show', `:${file}`).stdout }));
  }
  return git('ls-files', '-z').stdout.split('\0').filter(Boolean).filter(f => existsSync(f)).map(file => ({ file, text: readFileSync(file, 'utf8') }));
}

const HOW = `How to fix it: split the file by job, not by size, so each new file has one reason to change and a name that says
what is in it (e.g. engine.cpp → engine_notes.cpp, engine_hits.cpp, engine_render.cpp; a long test file → one file per
area). Keep the old file as the entry point; move shared helpers to a small private header or module; move whole
functions and their comments, unchanged. Then build and run the same tests as before, and run \`pnpm bd size baseline\`
so the baseline drops with it. Never shrink a file by deleting comments or squeezing lines.`;

const cmd = process.argv[2] ?? 'check';
if (cmd === 'install') {
  console.log(JSON.stringify({ installed: installPreCommitHook() }));
} else if (cmd === 'baseline') {
  const over: Baseline = {};
  for (const { file, text } of files(false)) if (counted(file, text) && tokens(Buffer.byteLength(text)) > LIMIT_TOKENS) over[file] = tokens(Buffer.byteLength(text));
  const sorted = Object.fromEntries(Object.entries(over).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(BASELINE, JSON.stringify(sorted, null, 2) + '\n');
  console.log(JSON.stringify({ baseline: BASELINE, files: Object.keys(sorted).length }));
} else if (cmd === 'check') {
  const staged = process.argv.includes('--staged'), base = readBaseline();
  const over: { file: string; tokens: number; allowed: number }[] = [], shrunk: string[] = [];
  let checked = 0;
  for (const { file, text } of files(staged)) {
    if (!counted(file, text)) continue;
    checked++;
    const t = tokens(Buffer.byteLength(text)), allowed = Math.max(LIMIT_TOKENS, base[file] ?? 0);
    if (t > allowed) over.push({ file, tokens: t, allowed });
    else if (base[file] !== undefined && t < base[file]) shrunk.push(file);
  }
  console.log(JSON.stringify({ checked, limit: LIMIT_TOKENS, over, shrunk }));
  if (shrunk.length) console.error(`Smaller than their baseline (run \`pnpm bd size baseline\` to lock that in): ${shrunk.join(', ')}`);
  if (over.length) {
    console.error(`\nToo big (about ${LIMIT_TOKENS} tokens = ${LIMIT_TOKENS * BYTES_PER_TOKEN} bytes per file; files already over may not grow):`);
    for (const o of over) console.error(`  ${o.file}: ~${o.tokens} tokens (allowed ${o.allowed})`);
    console.error(`\n${HOW}\n`);
    process.exit(1);
  }
} else throw new Error('usage: pnpm bd size check [--staged] | baseline | install');
